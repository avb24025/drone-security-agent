"""
app/models/db_models.py
───────────────────────
SQLAlchemy ORM models for every database entity.

Tables
──────
  frames   – raw telemetry and description for every processed drone frame
  events   – structured objects / activities extracted from each frame
  alerts   – security alerts produced by the alert engine
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import (
    JSON,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class Frame(Base):
    """One drone frame with its raw telemetry and AI-generated analysis."""

    __tablename__ = "frames"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    # Drone-supplied telemetry fields
    frame_id: Mapped[int] = mapped_column(Integer, unique=True, nullable=False, index=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    location: Mapped[str] = mapped_column(String(255), nullable=False, index=True)
    altitude: Mapped[float] = mapped_column(Float, nullable=True)
    latitude: Mapped[float] = mapped_column(Float, nullable=True)
    longitude: Mapped[float] = mapped_column(Float, nullable=True)

    # Raw description submitted with the frame
    original_description: Mapped[str] = mapped_column(Text, nullable=False)

    # Full JSON blob returned by Gemini (stored for reference / debugging)
    gemini_analysis: Mapped[dict | None] = mapped_column(JSON, nullable=True)

    processed_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), nullable=False
    )

    # Relationships
    events: Mapped[list["Event"]] = relationship(
        "Event", back_populates="frame", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<Frame id={self.id} frame_id={self.frame_id} location={self.location!r}>"


class Event(Base):
    """
    One structured security event extracted from a frame.

    A single frame can produce multiple events (e.g. a person AND a vehicle
    detected at the same time).
    """

    __tablename__ = "events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    # Parent frame reference
    frame_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("frames.frame_id", ondelete="CASCADE"), nullable=False, index=True
    )

    timestamp: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    location: Mapped[str] = mapped_column(String(255), nullable=False, index=True)

    # Extracted object fields
    object_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    object_attributes: Mapped[dict | None] = mapped_column(JSON, nullable=True)

    # What was happening
    activity: Mapped[str | None] = mapped_column(String(255), nullable=True)
    event_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Relationships
    frame: Mapped["Frame"] = relationship("Frame", back_populates="events")
    alerts: Mapped[list["Alert"]] = relationship(
        "Alert", back_populates="event", cascade="all, delete-orphan"
    )

    __table_args__ = (
        Index("ix_events_object_type_location", "object_type", "location"),
    )

    def __repr__(self) -> str:
        return (
            f"<Event id={self.id} frame_id={self.frame_id} "
            f"type={self.event_type!r} object={self.object_type!r}>"
        )


class Alert(Base):
    """Security alert generated by the rule engine."""

    __tablename__ = "alerts"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    # Optional link back to the triggering event
    event_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("events.id", ondelete="SET NULL"), nullable=True, index=True
    )

    alert_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    severity: Mapped[str] = mapped_column(String(20), nullable=False, index=True)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    timestamp: Mapped[datetime] = mapped_column(DateTime, nullable=False, index=True)
    location: Mapped[str] = mapped_column(String(255), nullable=False)

    # frame_id is denormalised here for fast queries without joining through Event.
    frame_id: Mapped[int | None] = mapped_column(Integer, nullable=True)

    # Deduplication key: prevents the same rule firing twice for the same event.
    dedup_key: Mapped[str | None] = mapped_column(String(512), nullable=True, unique=True)

    # Workflow status
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="unread", index=True)

    # Relationships
    event: Mapped["Event | None"] = relationship("Event", back_populates="alerts")

    __table_args__ = (
        Index("ix_alerts_severity_status", "severity", "status"),
    )

    def __repr__(self) -> str:
        return (
            f"<Alert id={self.id} type={self.alert_type!r} "
            f"severity={self.severity!r} status={self.status!r}>"
        )
